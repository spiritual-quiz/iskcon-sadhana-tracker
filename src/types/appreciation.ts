export type AppreciationCategory =
  | 'Consistent Sadhana'
  | 'Japa Commitment'
  | 'Reading Habit'
  | 'Hearing Habit'
  | 'Morning Programme Participation'
  | 'Weekly Class Participation'
  | 'Monthly Satsanga Participation'
  | 'Sadhana Improvement'
  | 'Consistency Milestone';

export interface AppreciationCard {
  id: string;
  userId: string;
  counseleeName: string;
  category: AppreciationCategory;
  period: string; // e.g. "Week of Oct 5 - 11, 2026" or "October 2026"
  achievement: string; // e.g. "Completed all 16 rounds before 7 AM every day"
  message: string; // e.g. "Congratulations! Your dedication to morning japa is deeply inspiring."
  isPublished: boolean;
  isSuggested: boolean; // generated by automatic candidate detector
  counseleeConsent: boolean; // whether devotee consented to public recognition
  publishedAt?: string;
  createdAt: string;
}
